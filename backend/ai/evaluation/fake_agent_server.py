"""Development-only Nobel Explorer API with a SCRIPTED language model (no OpenAI).

    set -a; . ./.env.docker; set +a; export DB_HOST=127.0.0.1 DB_PORT=9303 TOKENIZERS_PARALLELISM=false
    .venv-ai/bin/python -m backend.ai.evaluation.fake_agent_server [--port 8000]

What is real and what is scripted
---------------------------------
Real: the FastAPI application (every existing route and ``POST /ai/chat``),
request validation, the agent loop (``run_agent``), budgets and middleware,
the four validated tools, read-only MySQL queries, ChromaDB retrieval with the
real embedding model, the evidence registry and the citation validator.

Scripted: only the language model's decisions. ``ScriptedChatModel`` follows a
fixed tool plan per supported question (the Phase 3 ``fake_plan`` from
``agent_eval_set.json``) and composes an evidence-only answer from the actual
tool results. Answers are therefore NOT generated by an LLM and say nothing
about real-model quality.

Safety
------
* Not imported by ``backend.main``; the production app is unchanged. Overrides
  are applied to this process's app instance only, via FastAPI
  ``dependency_overrides`` on ``get_agent_config`` / ``get_agent_runner``.
* Binds to loopback only; any other host is refused.
* Never constructs ``ChatOpenAI``: ``OPENAI_API_KEY`` is removed from this
  process, and ``build_chat_model`` is replaced by a function that raises.
* Unsupported questions fail closed with a 503 "unavailable" response; there
  is no fallback to a real provider.
* ``.env`` is not read. Database access by the tools uses the Phase 1
  ``read_only_session`` (MySQL READ ONLY transactions).
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
from pathlib import Path
from typing import Any

from pydantic import SecretStr

from backend.ai.agent.config import AgentConfig
from backend.ai.agent.schemas import ChatResponse, ErrorInfo

DATASET = Path(__file__).with_name("agent_eval_set.json")

# The model name reported in responses, so scripted output is never mistaken
# for a real model's output. Satisfies AgentConfig's model-name pattern.
SCRIPTED_MODEL_NAME = "scripted-dev-model"
# availability() requires a non-empty key. This placeholder is never sent
# anywhere: the scripted model is always passed to run_agent explicitly.
PLACEHOLDER_KEY = "scripted-model-no-provider"

UNSUPPORTED_MESSAGE = (
    "This development server only answers scripted questions; no real language model is available."
)

# Wording used in the UI (suggested questions and the Phase 4D.1 end-to-end
# list) that differs from the evaluation dataset -> evaluation case id.
QUESTION_ALIASES = {
    "who won the 2022 chemistry prize": "R01",
    "which three birth countries have the most nobel laureates": "R05",
    "how do solar cells convert sunlight into electricity": "R07",
    "why did albert einstein receive the nobel prize": "R02",
}

# Data-freshness regression (Phase 4D.1). The local database ends in 2025; the
# scripted answer must acknowledge coverage rather than claim no prize exists.
FRESHNESS_CASES = {
    "who won the 2026 chemistry prize": [[{"tool": "search_laureates", "args": {"year": 2026, "category": "Chemistry"}}]],
    "who won the 2026 nobel prize in chemistry": [[{"tool": "search_laureates", "args": {"year": 2026, "category": "Chemistry"}}]],
}
FRESHNESS_NOTE = (
    "Nobel Explorer's local records only include prizes up to the latest year imported, so a more recent "
    "prize may exist that is not in this database yet. The absence of a record here does not mean the prize "
    "was not awarded; please check an up-to-date official source."
)


def normalise_question(question: str) -> str:
    text = " ".join(str(question).lower().split())
    return re.sub(r"[\s?.!]+$", "", text)


def load_plans(dataset_path: Path = DATASET) -> dict[str, dict[str, Any]]:
    """Normalised question -> {"case_id", "steps", "freshness"}."""
    cases = json.loads(dataset_path.read_text(encoding="utf-8"))["cases"]
    by_id = {case["id"]: case for case in cases}
    plans = {normalise_question(c["question"]): {"case_id": c["id"], "steps": c["fake_plan"], "freshness": False}
             for c in cases if c.get("fake_plan")}
    for alias, case_id in QUESTION_ALIASES.items():
        plans[alias] = {"case_id": case_id, "steps": by_id[case_id]["fake_plan"], "freshness": False}
    for question, steps in FRESHNESS_CASES.items():
        plans[question] = {"case_id": "F2026", "steps": steps, "freshness": True}
    return plans


def scripted_config() -> AgentConfig:
    return AgentConfig(enabled=True, openai_api_key=SecretStr(PLACEHOLDER_KEY), model=SCRIPTED_MODEL_NAME)


def _refuse_real_provider(*_args, **_kwargs):
    raise RuntimeError("The development fake server never constructs a real language-model client.")


def make_scripted_runner(plans: dict[str, dict[str, Any]], tool_context=None):
    from backend.ai.agent.service import run_agent
    from backend.ai.agent.testing import ScriptedChatModel, compose_answer, planned_policy

    def freshness_compose(envelopes, question=""):
        return f"{compose_answer(envelopes, question)}\n{FRESHNESS_NOTE}"

    async def runner(question: str, config: AgentConfig, request_id: str) -> ChatResponse:
        plan = plans.get(normalise_question(question))
        if plan is None:
            # Fail closed: never fall back to a real provider.
            return ChatResponse(request_id=request_id, status="unavailable", model=config.model,
                                error=ErrorInfo(type="unavailable", message=UNSUPPORTED_MESSAGE))
        compose = freshness_compose if plan["freshness"] else compose_answer
        model = ScriptedChatModel(policy=planned_policy(plan["steps"], compose=compose))
        return await run_agent(question, config=config, chat_model=model, tool_context=tool_context,
                               request_id=request_id)

    return runner


def create_dev_app(tool_context=None, plans: dict[str, dict[str, Any]] | None = None):
    """Return the real application with the scripted model wired in (this process only)."""
    os.environ.pop("OPENAI_API_KEY", None)
    import backend.ai.agent.service as service
    from backend.main import app
    from backend.routes import ai as ai_route

    service.build_chat_model = _refuse_real_provider
    runner = make_scripted_runner(plans or load_plans(), tool_context)
    app.dependency_overrides[ai_route.get_agent_config] = scripted_config
    app.dependency_overrides[ai_route.get_agent_runner] = lambda: runner
    # Scripted model, no spending: limits would only slow repeated local test runs.
    from backend.ai.guard import AIGuard, GuardConfig

    dev_guard = AIGuard(GuardConfig(per_ip_per_minute=10_000, per_ip_per_day=100_000, global_per_day=100_000,
                                    max_concurrent=100, daily_spend_limit_usd=1e6, monthly_spend_limit_usd=1e6))
    app.dependency_overrides[ai_route.get_ai_guard] = lambda: dev_guard
    return app


def require_loopback(host: str) -> str:
    if host == "localhost":
        return host
    try:
        if ipaddress.ip_address(host).is_loopback:
            return host
    except ValueError:
        pass
    raise SystemExit(f"Refusing to bind the development fake server to non-loopback host {host!r}.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Development-only Nobel Explorer API with a scripted model")
    parser.add_argument("--host", default="127.0.0.1", help="loopback address only")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args(argv)
    host = require_loopback(args.host)

    import uvicorn

    app = create_dev_app()
    print(f"Scripted (fake) model on http://{host}:{args.port} - answers are NOT from a real LLM.")
    print(f"Supported questions: {len(load_plans())}. Unsupported questions return 503.")
    uvicorn.run(app, host=host, port=args.port, log_level="info")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
